// Smart picker — avoids repeating recent messages
export function pickMessage(
  category: MotivationCategory,
  recentIds: string[] = []  // last 5 shown IDs
): MotivationMessage {
  const pool = MOTIVATION_MESSAGES.filter(
    m => m.category === category && !recentIds.includes(m.id)
  )
  // fallback: use full category if all recently shown
  const source = pool.length > 0
    ? pool
    : MOTIVATION_MESSAGES.filter(m => m.category === category)
  return source[Math.floor(Math.random() * source.length)]
}

// Time-based category picker
export function categoryForTime(hour: number): MotivationCategory {
  if (hour >= 5 && hour < 10) return 'start'
  if (hour >= 10 && hour < 20) return 'grind'
  if (hour >= 20 || hour < 5) return 'late_night'
  return 'grind'  // unreachable fallback
}
